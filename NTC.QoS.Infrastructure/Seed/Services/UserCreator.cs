using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using NTC.QoS.Domain.Entities;
using NTC.QoS.Domain.Interfaces;
using NTC.QoS.Infrastructure.Persistence;
using NTC.QoS.Infrastructure.Seed.Interfaces;

namespace NTC.QoS.Infrastructure.Seed.Services;

public class UserCreator : IUserCreator
{
    private readonly ApplicationDbContext _context;
    private readonly ILogger<UserCreator> _logger;

    public UserCreator(ApplicationDbContext context, ILogger<UserCreator> logger)
    {
        _context = context;
        _logger = logger;
    }

    public async Task<User> CreateNewUserAsync(ValidatedConfiguration config, string password)
    {
        _logger.LogInformation("Creating default admin user with email: {Email}", config.Email);

        // Get the SuperAdmin role and National organization
        var superAdminRole = await GetSuperAdminRoleAsync();
        var nationalOrganization = await GetNationalOrganizationAsync();

        // Create user in Clerk
        _logger.LogInformation("Creating user in Clerk with email: {Email}", config.Email);
        var clerkUserPayload = new CreateClerkUserPayload
        {
            EmailAddress = config.Email,
            FirstName = config.FirstName,
            LastName = config.LastName,
            Password = password,
            PublicMetadata = new Dictionary<string, object>
            {
                { "role", superAdminRole.Key },
                { "organization", nationalOrganization.Name },
                { "isDefaultAdmin", true }
            },
            PrivateMetadata = new Dictionary<string, object>
            {
                { "created_by_seeder", true },
                { "created_at", DateTime.UtcNow.ToString("O") }
            }
        };

        var clerkUser = await config.ClerkUserService.CreateUserAsync(clerkUserPayload);
        var authUserId = clerkUser.Id;
        _logger.LogInformation("Successfully created user in Clerk with ID: {ClerkUserId}", authUserId);

        // Create user in local database
        _logger.LogInformation("Creating user in local database...");
        var newUser = new User
        {
            Id = UserSeeder.DefaultAdminUserId,
            RoleId = superAdminRole.Id,
            OrganizationId = nationalOrganization.Id,
            AuthUserId = authUserId,
            Email = config.Email,
            CreatedAt = DateTime.UtcNow,
            CreatedBy = "System",
            UpdatedAt = DateTime.UtcNow,
            UpdatedBy = "System",
            IsDeleted = false
        };

        await _context.Users.AddAsync(newUser);
        await _context.SaveChangesAsync();

        _logger.LogInformation("Successfully created default admin user with email: {Email} and AuthUserId: {AuthUserId}",
            config.Email, authUserId);

        // Log password information securely only if we generated it automatically (not provided via config/env)
        if (config.PasswordWasAutoGenerated)
        {
            _logger.LogCritical("IMPORTANT: A password for the admin user {Email} was auto-generated and is shown below. This password is only displayed ONCE in logs. Please store it securely and change it as soon as possible. You may also set a password using the 'DefaultAdmin:Password' configuration (User Secrets or 'DefaultAdmin__Password' environment variable) and restart the application to ensure you can log in.",
                config.Email);
            _logger.LogCritical("AUTO-GENERATED PASSWORD for {Email}: {Password}", config.Email, password);
        }

        return newUser;
    }

    private async Task<Role> GetSuperAdminRoleAsync()
    {
        var superAdminRole = await _context.Roles.AsNoTracking()
            .FirstOrDefaultAsync(r => r.Key == "super_admin");

        if (superAdminRole == null)
        {
            throw new InvalidOperationException(
                "CRITICAL ERROR: SuperAdmin role (key: 'super_admin') not found in database. " +
                "Cannot create default admin user without SuperAdmin role. " +
                "Ensure role seeding has completed successfully before user seeding.");
        }

        return superAdminRole;
    }

    private async Task<Organization> GetNationalOrganizationAsync()
    {
        var nationalOrganization = await _context.Organizations.AsNoTracking()
            .FirstOrDefaultAsync(o => o.Name == "National");

        if (nationalOrganization == null)
        {
            throw new InvalidOperationException(
                "CRITICAL ERROR: National organization not found in database. " +
                "Cannot create default admin user without National organization. " +
                "Ensure organization seeding has completed successfully before user seeding.");
        }

        return nationalOrganization;
    }
}