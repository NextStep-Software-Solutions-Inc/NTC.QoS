using Microsoft.Extensions.Configuration;
using NTC.QoS.Domain.Interfaces;
using NTC.QoS.Infrastructure.Seed.Interfaces;

namespace NTC.QoS.Infrastructure.Seed.Services;

public class ConfigurationValidator : IConfigurationValidator
{
    private readonly IConfiguration _configuration;
    private readonly IClerkUserService _clerkUserService;
    private readonly IPasswordGenerator _passwordGenerator;

    public ConfigurationValidator(IConfiguration configuration, IClerkUserService clerkUserService, IPasswordGenerator passwordGenerator)
    {
        _configuration = configuration;
        _clerkUserService = clerkUserService;
        _passwordGenerator = passwordGenerator;
    }

    public Task<ValidatedConfiguration> ValidateAsync()
    {
        // CRITICAL: Email is required - no fallback allowed
        var email = _configuration.GetSection("DefaultAdmin:Email").Value;
        if (string.IsNullOrWhiteSpace(email))
        {
            throw new InvalidOperationException(
                "CRITICAL ERROR: DefaultAdmin:Email configuration is missing or empty. " +
                "The application cannot start without a configured default admin email. " +
                "Please set 'DefaultAdmin:Email' in your configuration (appsettings.json, user secrets, or environment variables).");
        }

        var firstName = _configuration.GetSection("DefaultAdmin:FirstName").Value ?? "System";
        var lastName = _configuration.GetSection("DefaultAdmin:LastName").Value ?? "Administrator";

        // Capture config/env password values once to avoid redundant lookups later
        var configuredPassword = _configuration.GetSection("DefaultAdmin:Password").Value;
        var envPassword = Environment.GetEnvironmentVariable("DEFAULT_ADMIN_PASSWORD");

        // Priority order for password: User Secrets > Environment Variable > Generated (for dev or first run)
        var password = configuredPassword ?? envPassword ?? _passwordGenerator.GenerateSecurePassword();
        var passwordWasAutoGenerated = string.IsNullOrEmpty(configuredPassword) && string.IsNullOrEmpty(envPassword);

        // CRITICAL: Clerk configuration must be valid - no skipping allowed
        var clerkSecretKey = _configuration.GetSection("Clerk:SecretKey").Value;
        if (!IsValidClerkSecret(clerkSecretKey))
        {
            throw new InvalidOperationException(
                "CRITICAL ERROR: Clerk:SecretKey configuration is missing or invalid (must start with 'sk_'). " +
                "The application cannot start without a valid Clerk secret key. " +
                "Please set 'Clerk:SecretKey' in your configuration with a valid Clerk secret key.");
        }

        if (_clerkUserService == null)
        {
            throw new InvalidOperationException(
                "CRITICAL ERROR: IClerkUserService is not available. " +
                "The application cannot start without Clerk user service configured. " +
                "Please ensure Clerk services are properly registered in dependency injection.");
        }
        var validatedConfiguration = new ValidatedConfiguration(email, firstName, lastName, password, passwordWasAutoGenerated, clerkSecretKey!, _clerkUserService);
        return Task.FromResult(validatedConfiguration);
    }

    private static bool IsValidClerkSecret(string? key) => !string.IsNullOrWhiteSpace(key) && key.StartsWith("sk_");
}