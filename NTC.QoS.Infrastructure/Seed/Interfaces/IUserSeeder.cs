using NTC.QoS.Domain.Entities;
using NTC.QoS.Domain.Interfaces;

namespace NTC.QoS.Infrastructure.Seed.Interfaces;

public interface IUserSeeder
{
    Task SeedAsync();
}

public interface IConfigurationValidator
{
    Task<ValidatedConfiguration> ValidateAsync();
}

public interface IPasswordGenerator
{
    string GenerateSecurePassword();
}

public interface IUserCreator
{
    Task<User> CreateNewUserAsync(ValidatedConfiguration config, string password);
}

public interface IUserUpdater
{
    Task UpdateExistingUserAsync(User existingUser, ValidatedConfiguration config, string password);
}

public record ValidatedConfiguration(
    string Email,
    string FirstName,
    string LastName,
    string Password,
    bool PasswordWasAutoGenerated,
    string ClerkSecretKey,
    IClerkUserService ClerkUserService
);