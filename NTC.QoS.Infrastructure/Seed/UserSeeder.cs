using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.Logging;
using NTC.QoS.Domain.Entities;
using NTC.QoS.Domain.Interfaces;
using NTC.QoS.Infrastructure.Persistence;
using System.Security.Cryptography;

namespace NTC.QoS.Infrastructure.Seed;

public static class UserSeeder
{
    // Fixed UUID for consistent default admin user seeding
    public static readonly Guid DefaultAdminUserId = Guid.Parse("99999999-9999-9999-9999-999999999999");

    private static bool IsValidClerkSecret(string? key) => !string.IsNullOrWhiteSpace(key) && key.StartsWith("sk_");

    // Seeds a default admin user into the database and Clerk
    // Throws exception if the default admin user cannot be created or verified
    public static async Task SeedAsync(ApplicationDbContext context, IClerkUserService? clerkUserService, IConfiguration configuration, ILogger logger)
    {
        logger.LogInformation("Starting User seeding process...");
        await SeedDefaultAdminUserAsync(context, clerkUserService, configuration, logger);
        logger.LogInformation("User seeding process completed successfully.");
    }

    // Seeds a default admin user from configuration
    // Throws exception if the user cannot be created or verified
    private static async Task SeedDefaultAdminUserAsync(ApplicationDbContext context, IClerkUserService? clerkUserService, IConfiguration configuration, ILogger logger)
    {
        logger.LogInformation("Checking if default admin user needs to be seeded...");

        // CRITICAL: Email is required - no fallback allowed
        var defaultAdminEmail = configuration.GetSection("DefaultAdmin:Email").Value;
        if (string.IsNullOrWhiteSpace(defaultAdminEmail))
        {
            const string message = "CRITICAL ERROR: DefaultAdmin:Email configuration is missing or empty. " +
                "The application cannot start without a configured default admin email. " +
                "Please set 'DefaultAdmin:Email' in your configuration (appsettings.json, user secrets, or environment variables).";
            logger.LogCritical(message);
            throw new InvalidOperationException(message);
        }

        var defaultAdminFirstName = configuration.GetSection("DefaultAdmin:FirstName").Value ?? "System";
        var defaultAdminLastName = configuration.GetSection("DefaultAdmin:LastName").Value ?? "Administrator";

        // Capture config/env password values once to avoid redundant lookups later
        var configuredPassword = configuration.GetSection("DefaultAdmin:Password").Value; // User Secrets / appsettings / env-injected
        var envPassword = Environment.GetEnvironmentVariable("DEFAULT_ADMIN_PASSWORD");

        // Priority order for password: User Secrets > Environment Variable > Generated (for dev or first run)
        var defaultAdminPassword = configuredPassword ?? envPassword ?? GenerateSecureDefaultPassword();
        var passwordWasAutoGenerated = string.IsNullOrEmpty(configuredPassword) && string.IsNullOrEmpty(envPassword);

        // CRITICAL: Clerk configuration must be valid - no skipping allowed
        var clerkSecretKey = configuration.GetSection("Clerk:SecretKey").Value;
        if (!IsValidClerkSecret(clerkSecretKey))
        {
            const string message = "CRITICAL ERROR: Clerk:SecretKey configuration is missing or invalid (must start with 'sk_'). " +
                "The application cannot start without a valid Clerk secret key. " +
                "Please set 'Clerk:SecretKey' in your configuration with a valid Clerk secret key.";
            logger.LogCritical(message);
            throw new InvalidOperationException(message);
        }

        if (clerkUserService == null)
        {
            const string message = "CRITICAL ERROR: IClerkUserService is not available. " +
                "The application cannot start without Clerk user service configured. " +
                "Please ensure Clerk services are properly registered in dependency injection.";
            logger.LogCritical(message);
            throw new InvalidOperationException(message);
        }

        logger.LogInformation("Clerk configuration validated successfully.");

        // Check if default admin user already exists in database
        var existingUser = await context.Users.AsNoTracking()
            .FirstOrDefaultAsync(u => u.Email == defaultAdminEmail || u.Id == DefaultAdminUserId);

        if (existingUser is not null)
        {
            logger.LogInformation("Default admin user already exists in database with email: {Email}", existingUser.Email);

            // If user has placeholder AuthUserId, update it with real Clerk integration
            if (existingUser.AuthUserId.StartsWith("clerk_placeholder_"))
            {
                logger.LogInformation("Existing user has placeholder AuthUserId. Updating with Clerk integration...");
                await UpdateExistingUserWithClerkIntegration(context, clerkUserService, existingUser, defaultAdminPassword, logger);
            }
            else
            {
                logger.LogInformation("Default admin user is properly configured with Clerk AuthUserId: {AuthUserId}", existingUser.AuthUserId);
            }
            return; // User exists and is properly configured
        }

        logger.LogInformation("Creating default admin user with email: {Email}", defaultAdminEmail);

        try
        {
            // Get the SuperAdmin role and National organization
            var superAdminRole = await context.Roles.AsNoTracking()
                .FirstOrDefaultAsync(r => r.Key == "super_admin");

            if (superAdminRole is null)
            {
                const string message = "CRITICAL ERROR: SuperAdmin role (key: 'super_admin') not found in database. " +
                    "Cannot create default admin user without SuperAdmin role. " +
                    "Ensure role seeding has completed successfully before user seeding.";
                logger.LogCritical(message);
                throw new InvalidOperationException(message);
            }

            var nationalOrganization = await context.Organizations.AsNoTracking()
                .FirstOrDefaultAsync(o => o.Name == "National");

            if (nationalOrganization is null)
            {
                const string message = "CRITICAL ERROR: National organization not found in database. " +
                    "Cannot create default admin user without National organization. " +
                    "Ensure organization seeding has completed successfully before user seeding.";
                logger.LogCritical(message);
                throw new InvalidOperationException(message);
            }

            // Create user in Clerk
            logger.LogInformation("Creating user in Clerk with email: {Email}", defaultAdminEmail);
            var clerkUserPayload = new CreateClerkUserPayload
            {
                EmailAddress = defaultAdminEmail,
                FirstName = defaultAdminFirstName,
                LastName = defaultAdminLastName,
                Password = defaultAdminPassword,
                PublicMetadata = new Dictionary<string, object>
                {
                    { "role", superAdminRole.Key },
                    { "organization", nationalOrganization.Name },
                    { "isDefaultAdmin", true }
                },
                PrivateMetadata = new Dictionary<string, object>
                {
                    { "created_by_seeder", true },
                    { "created_at", DateTime.UtcNow.ToString("O") }
                }
            };

            // ClerkUserService.CreateUserAsync already calls EnsureSuccessStatusCode and throws on failure
            var clerkUser = await clerkUserService.CreateUserAsync(clerkUserPayload);
            var authUserId = clerkUser.Id;
            logger.LogInformation("Successfully created user in Clerk with ID: {ClerkUserId}", authUserId);

            // Create user in local database
            logger.LogInformation("Creating user in local database...");
            var newUser = new User
            {
                Id = DefaultAdminUserId,
                RoleId = superAdminRole.Id,
                OrganizationId = nationalOrganization.Id,
                AuthUserId = authUserId,
                Email = defaultAdminEmail,
                CreatedAt = DateTime.UtcNow,
                CreatedBy = "System",
                UpdatedAt = DateTime.UtcNow,
                UpdatedBy = "System",
                IsDeleted = false
            };

            await context.Users.AddAsync(newUser);
            await context.SaveChangesAsync();

            logger.LogInformation("Successfully created default admin user with email: {Email} and AuthUserId: {AuthUserId}",
                defaultAdminEmail, authUserId);

            // Log password information securely only if we generated it automatically (not provided via config/env)
            if (passwordWasAutoGenerated)
            {
                logger.LogCritical("IMPORTANT: A password for the admin user {Email} was auto-generated and is shown below. This password is only displayed ONCE in logs. Please store it securely and change it as soon as possible. You may also set a password using the 'DefaultAdmin:Password' user secret or the 'DEFAULT_ADMIN_PASSWORD' environment variable and restart the application to ensure you can log in.",
                    defaultAdminEmail);
                logger.LogCritical("AUTO-GENERATED PASSWORD for {Email}: {Password}", defaultAdminEmail, defaultAdminPassword);
            }
        }
        catch (Exception ex)
        {
            var message = $"CRITICAL ERROR: Failed to create default admin user. Error: {ex.Message}. " +
                "The application cannot start without a default admin user. " +
                "Please check the logs for detailed error information and ensure all dependencies " +
                "(Clerk service, database connection, required roles and organizations) are properly configured.";
            logger.LogCritical(ex, message);
            throw new InvalidOperationException(message, ex);
        }
    }

    /// <summary>
    /// Updates an existing user with placeholder AuthUserId to use real Clerk integration
    /// </summary>
    private static async Task UpdateExistingUserWithClerkIntegration(
        ApplicationDbContext context,
        IClerkUserService clerkUserService,
        User existingUser,
        string password,
        ILogger logger)
    {
        try
        {
            logger.LogInformation("Updating existing admin user with Clerk integration...");

            var role = await context.Roles.AsNoTracking()
                .FirstOrDefaultAsync(r => r.Id == existingUser.RoleId);
            var organization = await context.Organizations.AsNoTracking()
                .FirstOrDefaultAsync(o => o.Id == existingUser.OrganizationId);

            var clerkUserPayload = new CreateClerkUserPayload
            {
                EmailAddress = existingUser.Email,
                FirstName = "System",
                LastName = "Administrator",
                Password = password,
                PublicMetadata = new Dictionary<string, object>
                {
                    { "role", role?.Key ?? "super_admin" },
                    { "organization", organization?.Name ?? "National" },
                    { "isDefaultAdmin", true }
                },
                PrivateMetadata = new Dictionary<string, object>
                {
                    { "created_by_seeder", true },
                    { "updated_from_placeholder", true },
                    { "updated_at", DateTime.UtcNow.ToString("O") }
                }
            };

            // ClerkUserService.CreateUserAsync already calls EnsureSuccessStatusCode and throws on failure
            var clerkUser = await clerkUserService.CreateUserAsync(clerkUserPayload);

            var userToUpdate = await context.Users.FirstOrDefaultAsync(u => u.Id == existingUser.Id);
            if (userToUpdate != null)
            {
                var oldAuthUserId = userToUpdate.AuthUserId;
                userToUpdate.AuthUserId = clerkUser.Id;
                userToUpdate.UpdatedAt = DateTime.UtcNow;
                userToUpdate.UpdatedBy = "System";

                await context.SaveChangesAsync();

                logger.LogInformation("Successfully updated admin user AuthUserId from {OldAuthUserId} to {NewAuthUserId}",
                    oldAuthUserId, clerkUser.Id);
            }
        }
        catch (Exception ex)
        {
            var message = $"CRITICAL ERROR: Failed to update existing user with Clerk integration. Error: {ex.Message}. " +
                "The application cannot start without proper Clerk integration for the default admin user.";
            logger.LogCritical(ex, message);
            throw new InvalidOperationException(message, ex);
        }
    }

    private static string GenerateSecureDefaultPassword()
    {
        // Character sets exclude visually ambiguous characters (I, L, O, 1, 0) to reduce transcription errors
        // when sharing credentials verbally or copying from logs. This improves readability and usability.
        const string uppercase = "ABCDEFGHJKLMNPQRSTUVWXYZ"; // Excludes I, L, O
        const string lowercase = "abcdefghijkmnpqrstuvwxyz"; // Excludes l, o
        const string digits = "023456789"; // Excludes 1, 0
        const string special = "!@#$%^&*";
        const string allChars = uppercase + lowercase + digits + special;

        var password = new char[16];

        // Ensure at least one of each type
        password[0] = uppercase[RandomNumberGenerator.GetInt32(uppercase.Length)];
        password[1] = lowercase[RandomNumberGenerator.GetInt32(lowercase.Length)];
        password[2] = digits[RandomNumberGenerator.GetInt32(digits.Length)];
        password[3] = special[RandomNumberGenerator.GetInt32(special.Length)];

        // Fill the rest randomly
        for (int i = 4; i < 16; i++)
        {
            password[i] = allChars[RandomNumberGenerator.GetInt32(allChars.Length)];
        }

        // Shuffle the password using Fisher-Yates shuffle
        for (int i = password.Length - 1; i > 0; i--)
        {
            int j = RandomNumberGenerator.GetInt32(i + 1);
            (password[i], password[j]) = (password[j], password[i]);
        }

        return new string(password);
    }
}