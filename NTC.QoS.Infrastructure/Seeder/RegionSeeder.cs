using Microsoft.EntityFrameworkCore; // Required for DbContext
using NetTopologySuite.Features; // Required for FeatureCollection
using NetTopologySuite.Geometries; // Required for MultiPolygon, Point
using NetTopologySuite.IO; // Required for GeoJsonSerializer
using NTC.QoS.Domain.Entities;
using NTC.QoS.Infrastructure.Persistence; // Adjust namespace to where your Region entity is located

namespace NTC.QoS.Infrastructure.Seeder; // Adjust namespace as per your project structure

public static class RegionSeeder
{
    // Path to your GeoJSON file relative to the application's output directory
    private const string GeoJsonFilePath = "Data/admin1.geojson";

    public static async Task SeedRegionsAsync(ApplicationDbContext dbContext) // Replace YourDbContext with your actual DbContext class name
    {

        // Check if any regions already exist to prevent duplicate seeding
        if (await dbContext.Regions.AnyAsync())
        {
            Console.WriteLine("Database already contains regions. Skipping seeding.");
            return;
        }

        Console.WriteLine($"Starting region seeding from {GeoJsonFilePath}...");

        FeatureCollection featureCollection = new FeatureCollection();

        try
        {

            string fullGeoJsonPath = Path.Combine(Environment.CurrentDirectory, GeoJsonFilePath);
            // Ensure the file exists
            if (!System.IO.File.Exists(fullGeoJsonPath))
            {
                Console.WriteLine($"Error: GeoJSON file not found at {fullGeoJsonPath}. Make sure it's copied to output directory.");
                return;
            }

            string geoJsonText = await System.IO.File.ReadAllTextAsync(fullGeoJsonPath);
            var serializer = GeoJsonSerializer.Create(); // Create a default GeoJsonSerializer instance
            using (var stringReader = new Newtonsoft.Json.JsonTextReader(new System.IO.StringReader(geoJsonText)))
            {

                // Deserialize the GeoJSON text into a FeatureCollection

                // Update the line causing the CS8600 warning
                featureCollection = serializer.Deserialize<FeatureCollection>(stringReader) ?? new FeatureCollection();
            }

            if (featureCollection == null || !featureCollection.Any())
            {
                Console.WriteLine("No features found in the GeoJSON file. Skipping seeding.");
                return;
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error reading or parsing GeoJSON file: {ex.Message}");
            Console.WriteLine(ex.StackTrace);
            return;
        }

        var regionsToAdd = new List<Region>();

        foreach (var feature in featureCollection)
        {
            // Ensure feature has geometry and properties
            if (feature?.Geometry == null || feature.Attributes == null)
            {
                Console.WriteLine("Skipping feature due to missing geometry or properties.");
                continue;
            }

            var region = new Region
            {
                // Id is generated by 'new Guid()' in the Region constructor (client-side)
                Name = feature.Attributes["ADM1_EN"]?.ToString() ?? string.Empty,
                Description = string.Empty,
                Code = feature.Attributes["ADM1_PCODE"]?.ToString() ?? string.Empty,
                Area = float.TryParse(feature.Attributes["AREA_SQKM"]?.ToString(), out float areaValue) ? areaValue : 0f
            };

            // Convert GeoJSON geometry to NetTopologySuite MultiPolygon
            if (feature.Geometry is MultiPolygon geoJsonMultiPolygon)
            {
                region.Boundaries = geoJsonMultiPolygon;
                // Calculate Center from Boundaries (Centroid of the MultiPolygon)
                region.Center = geoJsonMultiPolygon.Centroid;
            }
            else if (feature.Geometry is Polygon geoJsonPolygon) // Handle if a feature is just a Polygon, convert to MultiPolygon
            {
                region.Boundaries = new MultiPolygon(new[] { geoJsonPolygon });
                region.Center = geoJsonPolygon.Centroid;
            }
            else
            {
                Console.WriteLine($"Skipping feature '{region.Name}' due to unsupported geometry type: {feature.Geometry.GeometryType}");
                return;
            }

            regionsToAdd.Add(region);
        }

        try
        {
            await dbContext.Regions.AddRangeAsync(regionsToAdd);
            await dbContext.SaveChangesAsync();
            Console.WriteLine($"Successfully seeded {regionsToAdd.Count} regions into the database.");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error saving regions to database: {ex.Message}");
            Console.WriteLine(ex.InnerException?.Message); // Log inner exception for more details
            Console.WriteLine(ex.StackTrace);
        }
    }
}
